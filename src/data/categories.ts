export const categories: Category[] = Object.entries(categoryGroups).flatMap(
  ([disciplineId, titles]) =>
    titles.map((title) => ({
      id: `${disciplineId}-${slug(title)}`,
      disciplineId,
      title,
      description: `Practice ${title.toLowerCase()} with short visual drills, close answers, and review tracking.`,
      tags: [disciplineId, slug(title)],
    }))
);

export const getCategoriesForDiscipline = (disciplineId: string) =>
  categories.filter((category) => category.disciplineId === disciplineId);
